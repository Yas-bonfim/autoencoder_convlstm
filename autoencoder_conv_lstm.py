"""## Convert the data into binary voxel representation"""

threshold, upper, lower = 0.2, 1, 0
X_train = np.where(X_train>threshold, upper, lower)
X_test = np.where(X_test>threshold, upper, lower)

"""## Reshape the data to 3 dimensional dataset, which will be the input for the autoencoder"""

X_train = X_train.reshape(10000, 16,16,16,1)
X_test = X_test.reshape(2000,16,16,16,1)

activation = 'relu'
input_shape = (16,16,16,1)
layer_filters = [32, 16]
latent_layer = 4

inputs = Input(shape=input_shape, name='encoder_input')
x = (inputs)

# o filtro contém o número de neurônios Dense com ativação relu
for filters in layer_filters:
    x = layers.Conv3D(filters, (3,3,3), activation=activation, padding='same')(x)
    x = layers.MaxPooling3D((2,2,2), padding='same')(x)
    x = BatchNormalization()(x)

# gerando latent vector

x = layers.Conv3D(latent_layer, (3,3,3), activation=activation, padding='same')(x)
x = layers.MaxPooling3D((2,2,2), padding='same') (x)

encoded = tf.reshape(x, (-1,2,4,4))

# encoded = layers.TimeDistributed(layers.LSTM(10, input_shape=(4,4), return_sequences=True))(encoded)
# encoded = layers.TimeDistributed(layers.LSTM(6, return_sequences=True ))(encoded)
encoded = layers.TimeDistributed(layers.LSTM(latent_layer, return_sequences=True ))(encoded)

# instanciando modelo de encoder
encoder = Model(inputs,
                encoded,
                name='encoder')

encoder.summary()
plot_model(encoder, show_shapes=True)

encoded

latent_inputs = Input(shape=(encoded.shape[1:]), name='decoder_input')

x = layers.TimeDistributed(layers.LSTM(latent_layer, input_shape=(4,4), return_sequences=True))(latent_inputs)
# x = layers.TimeDistributed(layers.LSTM(16, return_sequences=True ))(x)
# x = layers.TimeDistributed(layers.LSTM(30, return_sequences=True ))(x)

re = tf.reshape(x, (-1,2,2,2,4))

x = layers.Conv3D(8, (3,3,3), activation=activation, padding='same')(re)
x = layers.UpSampling3D((2,2,2))(x)
x = BatchNormalization()(x)

# o filtro contém o número de neurônios dense com ativação relu
for filters in layer_filters[::-1]:
    x = layers.Conv3D(filters, (3,3,3), activation=activation, padding='same')(x)
    x = layers.UpSampling3D((2,2,2))(x)
    x = BatchNormalization()(x)

decoded = layers.Conv3D(1, (3,3,3), activation='sigmoid', padding='same')(x)

# instanciando modelo decoder
decoder = Model(latent_inputs, decoded, name='decoder')
decoder.summary()
plot_model(decoder, show_shapes=True)

# instanciando modelo autoencoder
autoencoder = Model(inputs,
                    decoder(encoder(inputs)),
                    name='autoencoder')
autoencoder.summary()
plot_model(autoencoder, show_shapes=True, rankdir='LR')

import timeit
from keras.callbacks import ReduceLROnPlateau, EarlyStopping
callbacks = [
    #          ReduceLROnPlateau(monitor="val_loss",
    # factor=0.00005,
    # patience=6,
    # verbose=1,
    # mode="min",
    # min_delta=0.001,
    # cooldown=0,
    # min_lr=0.0001
    #   ),
       EarlyStopping(
          monitor="val_loss",
          min_delta=0.0003,
          patience=20,
          verbose=1,
          mode="min",
          baseline=None,
          restore_best_weights=True,
      )
]

autoencoder.compile(optimizer='Adam', loss='binary_crossentropy')



"""## Train the Autoencoder for 100 Epochs"""

start = timeit.default_timer()

hist = autoencoder.fit(X_train, X_train,
                       epochs=130,
                       batch_size=500,
                       shuffle=True,
                       validation_data=(X_test, X_test))

stop = timeit.default_timer()

print(round(stop - start, 0))

scores = autoencoder.evaluate(X_test, X_test, verbose=0)

print(scores)

